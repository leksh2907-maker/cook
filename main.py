def get_team(team_id):
    t = db.teams.find_one({"team_id": team_id})
    if not t:
        raise HTTPException(404, "Team not found")
    return t


def remaining(t, level):
    key = str(level)
    if t.get("paused") and key in t.get("paused_remaining", {}):
        return max(0, int(t["paused_remaining"][key]))
    started = t.get("level_started", {}).get(key)
    if not started:
        return LEVELS[level]["seconds"]
    return max(0, int(started + LEVELS[level]["seconds"] - time.time()))


def event_settings():
    return db.settings.find_one({"_id": "event"}) or {"active": False, "verify_password": None}


