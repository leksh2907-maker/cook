def hash_pw(pw: str, salt: Optional[str] = None) -> str:
    salt = salt or secrets.token_hex(16)
    iterations = 240_000
    h = hashlib.pbkdf2_hmac("sha256", pw.encode(), salt.encode(), iterations).hex()
    return f"{salt}${iterations}${h}"


def check_pw(pw: str, stored: str) -> bool:
    """Accept legacy salt$hash (120k rounds) and current salt$rounds$hash hashes."""
    try:
        parts = stored.split("$")
        if len(parts) == 2:  # hashes generated by the first CFC build
            salt, digest = parts
            rounds = 120_000
        elif len(parts) == 3:
            salt, rounds_text, digest = parts
            rounds = int(rounds_text)
            if rounds < 100_000 or rounds > 2_000_000:
                return False
        else:
            return False
        candidate = hashlib.pbkdf2_hmac("sha256", pw.encode(), salt.encode(), rounds).hex()
        return hmac.compare_digest(candidate, digest)
    except (AttributeError, ValueError, TypeError):
        return False


