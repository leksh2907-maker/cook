@app.post("/api/level/{level}/start")
def start(level: int, team=Depends(current("team"))):
    if level not in LEVELS:
        raise HTTPException(404, "Unknown level")
    t = get_team(team)
    if level > t["unlocked"]:
        raise HTTPException(403, "Level locked")
    if str(level) in t["scores"]:
        raise HTTPException(409, "Level already completed")
    if not event_settings()["active"]:
        raise HTTPException(403, "Event has not started")
    if t["paused"]:
        raise HTTPException(403, "Team paused by admin")
    key = str(level)
    if key not in t["level_started"]:
        db.teams.update_one({"team_id": team}, {"$set": {f"level_started.{key}": time.time()}})
        t = get_team(team)
    rem = remaining(t, level)
    if rem <= 0:
        raise HTTPException(403, "Time is up")
    if level == 3:
        return {"remaining": rem, "challenges": [{"id": c["id"], "lang": c["lang"], "prompt": c["prompt"],
            "items": content.items_for(c)} for c in content.L3]}
    if level == 4:
        return {"remaining": rem, "problem": {k: content.L4[k] for k in ("title", "statement", "sample")}}
    if level == 5:
        a, b = content.L5A, content.L5B
        return {"remaining": rem, "parts": [
            {"id": "a", "kind": "recipe", "prompt": a["prompt"], "items": content.items_for(a, a["decoys"])},
            {"id": "b", "kind": "code", "lang": b["lang"], "prompt": b["prompt"], "items": content.items_for(b)}]}
    qs = [{"idx": q["idx"], "q": q["q"], "options": q["options"]}
          for q in db.questions.find({"level": level}).sort("idx")]
    return {"remaining": rem, "questions": qs}


def compute_score(level, answers):
    if not isinstance(answers, dict):
        raise HTTPException(422, "Answers must be an object")
    if level == 3:
        return sum(content.order_score(c, answers.get(c["id"])) for c in content.L3)
    if level == 5:
        return content.order_score(content.L5A, answers.get("a")) + content.order_score(content.L5B, answers.get("b"))
    if level == 4:
        lang, code = answers.get("lang"), answers.get("code", "")
        if lang not in ("c", "python") or not isinstance(code, str) or len(code) > 20000:
            raise HTTPException(422, "Provide valid C or Python code")
        passed = 0
        for tin, tout in content.L4["tests"]:
            r = runner.run(lang, code, tin + "\n")
            if r.get("stage") == "unavailable":
                raise HTTPException(503, r.get("stderr", "Isolated code runner unavailable"))
            passed += bool(r["ok"] and r["stdout"].strip() == tout)
        return passed * content.L4["points_per_test"]
    questions = list(db.questions.find({"level": level}))
    return sum(q["points"] for q in questions if answers.get(str(q["idx"])) == q["answer"])


@app.post("/api/level/4/run")
def run_code(b: RunReq, team=Depends(current("team"))):
    t = get_team(team)
    if t["unlocked"] < 4 or "4" not in t["level_started"] or t["paused"] or remaining(t, 4) <= 0:
        raise HTTPException(403, "Level 4 is not open")
    return runner.run(b.lang, b.code, b.stdin)


@app.post("/api/level/{level}/submit")
def submit(level: int, b: Answers, team=Depends(current("team"))):
    if level not in LEVELS:
        raise HTTPException(404, "Unknown level")
    t = get_team(team)
    key = str(level)
    if level > t["unlocked"] or key not in t["level_started"]:
        raise HTTPException(403, "Level not started")
    if t["paused"]:
        raise HTTPException(403, "Team paused")
    if key in t["scores"] or db.submissions.find_one({"team_id": team, "level": level}):
        raise HTTPException(409, "Already submitted")
    started = t.get("level_started", {}).get(key, 0)
    if remaining(t, level) <= 0 and time.time() > started + LEVELS[level]["seconds"] + 5:
        raise HTTPException(403, "Time is up")
    score = compute_score(level, b.answers)
    # Atomic unique index on (team_id, level) prevents double scoring on concurrent requests.
    try:
        db.submissions.insert_one({"team_id": team, "level": level, "answers": b.answers,
                                   "score": score, "at": time.time()})
    except Exception:
        raise HTTPException(409, "Already submitted")
    db.teams.update_one({"team_id": team}, {"$set": {f"scores.{key}": score,
        f"finished_at.{key}": time.time()}, "$max": {"unlocked": min(level + 1, max(LEVELS))}})
    return {"score": score, "max_score": LEVELS[level]["max"]}


@app.get("/api/leaderboard")
def leaderboard():
    rows = []
    for t in db.teams.find():
        finished = max(t.get("finished_at", {}).values(), default=0)
        rows.append({"team_id": t["team_id"], "name": t["name"], "completed": len(t.get("scores", {})),
            "score": sum(t.get("scores", {}).values()), "finished": finished,
            "status": "paused" if t.get("paused") else ("playing" if t.get("level_started") else "waiting")})
    rows.sort(key=lambda r: (-r["score"], r["finished"] or float("inf"), r["team_id"]))
    for i, row in enumerate(rows):
        row["rank"] = i + 1
        row.pop("finished")
    return rows


