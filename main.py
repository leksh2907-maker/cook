def token(sub: str, role: str) -> str:
    return jwt.encode({"sub": sub, "role": role, "exp": int(time.time()) + 6 * 3600}, JWT_SECRET, "HS256")


def current(role: str):
    def dep(authorization: str = Header(default="")):
        raw = authorization[7:] if authorization.startswith("Bearer ") else authorization
        try:
            p = jwt.decode(raw, JWT_SECRET, algorithms=["HS256"])
        except Exception:
            raise HTTPException(401, "Not signed in")
        if p.get("role") != role or not p.get("sub"):
            raise HTTPException(403, "Forbidden")
        # A valid token is not enough if the account was deleted after login.
        exists = db.teams.find_one({"team_id": p["sub"]}) if role == "team" else db.admins.find_one({"username": p["sub"]})
        if not exists:
            raise HTTPException(401, "Account no longer exists")
        return p["sub"]
    return dep


