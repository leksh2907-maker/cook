@app.post("/api/security/verify")
def verify(b: Verify, team=Depends(current("team"))):
    setting = event_settings()
    stored = setting.get("verify_password")
    ok = bool(stored and check_pw(b.password, stored))
    db.security_logs.insert_one({"team_id": team, "kind": "verify_ok" if ok else "verify_fail", "at": time.time()})
    if not ok:
        raise HTTPException(403, "Wrong verification password or verification is not configured")
    return {"ok": True}


