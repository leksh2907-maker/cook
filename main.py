@app.post("/api/admin/teams/{tid}/pause/{flag}")
def a_pause(tid: str, flag: int, _=Depends(current("admin"))):
    if flag not in (0, 1):
        raise HTTPException(400, "Pause flag must be 0 or 1")
    t = get_team(tid)
    if flag and not t.get("paused"):
        now = time.time()
        saved = {str(level): remaining(t, level) for level in LEVELS if str(level) in t.get("level_started", {}) and str(level) not in t.get("scores", {})}
        db.teams.update_one({"team_id": tid}, {"$set": {"paused": True, "paused_at": now, "paused_remaining": saved}})
    elif not flag and t.get("paused"):
        now = time.time()
        starts = dict(t.get("level_started", {}))
        for level, rem in t.get("paused_remaining", {}).items():
            starts[level] = now - (LEVELS[int(level)]["seconds"] - rem)
        db.teams.update_one({"team_id": tid}, {"$set": {"paused": False, "paused_at": None,
            "paused_remaining": {}, "level_started": starts}})
    return {"ok": True, "paused": bool(flag)}


